"""Hardware boundaries. Real implementations belong to P05/P07."""

from typing import Protocol


class Camera(Protocol):
    def capture(self, sequence: int) -> tuple[bytes, str]: ...


class LocationSource(Protocol):
    def sample(self) -> dict | None: ...


class PauseControl(Protocol):
    def is_paused(self) -> bool: ...


class Display(Protocol):
    def show(self, state: dict) -> None: ...


class Power(Protocol):
    def sample(self) -> tuple[int | None, bool | None]: ...


class ObjectProtection(Protocol):
    def write(self, capture_id: str, data: bytes) -> None: ...
    def read(self, capture_id: str) -> bytes: ...
    def delete(self, capture_id: str) -> None: ...


class SetupTransport(Protocol):
    def establish(self, challenge_id: str) -> str: ...
    def confirm_possession(self, session: str) -> str: ...


class DeviceTransport(Protocol):
    def request(self, method: str, path: str, payload: dict, key: str) -> dict: ...
    def put(self, url: str, data: bytes, headers: dict) -> int: ...
