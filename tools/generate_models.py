"""Generate language shapes from the closed v1 schema subset; validation is separate."""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFS = json.loads((ROOT / 'contracts/schema.json').read_text())['$defs']


def name(value):
    return {'Error': 'APIError', 'TimeZone': 'ZoneName'}.get(value, value)


def ts(schema):
    if '$ref' in schema:
        return name(schema['$ref'].split('/')[-1])
    if 'const' in schema:
        return json.dumps(schema['const'])
    if 'enum' in schema:
        return ' | '.join(json.dumps(v) for v in schema['enum'])
    if 'anyOf' in schema:
        return '(' + ' | '.join(ts(v) for v in schema['anyOf']) + ')'
    typ = schema.get('type')
    if typ == 'object':
        return '{ ' + '; '.join(f'{json.dumps(k)}{"" if k in schema["required"] else "?"}: {ts(v)}' for k, v in schema['properties'].items()) + ' }'
    if typ == 'array':
        return f'Array<{ts(schema["items"])}>'
    return {'integer': 'number', 'number': 'number', 'string': 'string', 'boolean': 'boolean', 'null': 'null'}[typ]


swift_nested = []


def sw(schema, hint):
    if '$ref' in schema:
        return name(schema['$ref'].split('/')[-1])
    if 'const' in schema:
        return 'String' if isinstance(schema['const'], str) else 'Int'
    if 'enum' in schema:
        return 'String'
    if 'anyOf' in schema:
        if len(schema['anyOf']) == 2 and schema['anyOf'][1].get('type') == 'null':
            return sw(schema['anyOf'][0], hint) + '?'
        return 'JSONValue'
    typ = schema.get('type')
    if typ == 'object':
        swift_nested.append(sw_struct(hint, schema))
        return hint
    if typ == 'array':
        return '[' + sw(schema['items'], hint + 'Item') + ']'
    return {'integer': 'Int', 'number': 'Double', 'string': 'String', 'boolean': 'Bool', 'null': 'JSONValue'}[typ]


def sw_struct(n, schema):
    fields = []
    for k, value in schema['properties'].items():
        t = sw(value, n + k[:1].upper() + k[1:])
        if k not in schema['required'] and not t.endswith('?'):
            t += '?'
        fields.append(f'    public var `{k}`: {t}')
    return f'public struct {n}: Codable, Sendable {{\n' + '\n'.join(fields) + '\n}'


def render():
    typescript = '// Generated by tools/generate_models.py. Do not edit.\n'
    typescript += '\n'.join(f'export type {name(n)} = {ts(s)};' for n, s in DEFS.items()) + '\n'
    swift = ['// Generated by tools/generate_models.py. Do not edit.', 'import Foundation']
    for n, s in DEFS.items():
        swift.append(sw_struct(name(n), s) if s.get('type') == 'object' else f'public typealias {name(n)} = {sw(s, name(n))}')
    swift.extend(swift_nested)
    swift.append('public enum WireDecoder {\n    public static func decodeShape(_ kind: String, data: Data) throws {\n        switch kind {')
    for n in DEFS:
        swift.append(f'        case "{n}": _ = try JSONDecoder().decode({name(n)}.self, from: data)')
    swift.append('        default: throw ContractFailure.invalid(kind)\n        }\n    }\n}')
    return {'services/backend/src/Wire.ts': typescript, 'apps/ios/Core/Sources/ClippyCore/Wire.swift': '\n\n'.join(swift) + '\n'}


if __name__ == '__main__':
    for path, content in render().items():
        target = ROOT / path
        if '--check' in sys.argv:
            if target.read_text() != content:
                raise SystemExit(f'Stale generated models: {path}')
        else:
            target.write_text(content)
